for (file in c("sma.R", "ema.R", "macd.R", "stdev.R", "linreg.R", "rsi.R", "stoch_rsi.R", "crossover.R", "crossunder.R")) source(file)
prices <- c(10, 12, 15, 20, 18, 22, 25, 24, 21)
stopifnot(isTRUE(all.equal(sma(prices, 3), c(37,47,53,60,65,71,70)/3)))
stopifnot(length(ema(prices, 3)) == 9, ema(prices, 3)[1] == 10)
stopifnot(max(abs(macd(prices, 3, 5, 2)$histogram - (macd(prices, 3, 5, 2)$macd_line - macd(prices, 3, 5, 2)$signal_line))) < 1e-9)
stopifnot(isTRUE(all.equal(stdev(c(2,4,4,4,5,5,7,9)), 2)))
fit <- linreg(c(2,4,6,8,10), 5, 0)
stopifnot(abs(fit$slope - 2) < 1e-9, abs(fit$intercept) < 1e-9)
stopifnot(length(rsi(prices, 3)) == length(prices))
long_prices <- cumsum(rep(c(1, 2, -1, 3, -2, -1, 2), 8)) + 50
stopifnot(length(stoch_rsi(long_prices, 5, 3, 3)$k_line) == length(long_prices))
stopifnot(identical(crossover(c(1,3,2),c(2,2,2)),c(FALSE,TRUE,FALSE)))
stopifnot(identical(crossunder(c(3,1,2),c(2,2,2)),c(FALSE,TRUE,FALSE)))
cat("All indicator checks passed.\n")
